/** 全部标签（保持出现顺序，去重），供筛选条使用 */
export function templateTags(): string[] {
  const seen = new Set<string>()
  const tags: string[] = []
  for (const t of TEMPLATES) {
    for (const tag of t.tags) {
      if (!seen.has(tag)) {
        seen.add(tag)
        tags.push(tag)
      }
    }
  }
  return tags
}

export function getTemplate(id: string): ExperimentTemplate | null {
  return TEMPLATES.find((t) => t.id === id) ?? null
}

/** 某个行业可用的模板；没有则返回空数组 */
export function templatesForIndustry(industryId: string): ExperimentTemplate[] {
  return TEMPLATES.filter((t) => t.industry === industryId)
}
