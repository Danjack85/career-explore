/**
 * 实验模板库 —— App 自己的方法内容（与测评题目同类，不是行业数据）。
 *
 * 为什么需要模板：
 *   产品要求用户「写一个可证伪的假设、设计每天 ≤ 30 分钟的任务」，
 *   但迷茫的学生恰恰做不到这两件事 —— 这正是他们卡住的原因。
 *   模板库把「一个像样的 7 天实验长什么样」直接摆出来让学生抄，
 *   先跑通一次闭环，再谈自己设计。
 *
 * 内容边界：
 *   - 每个模板都是**方法设计**：做什么、怎么记录、怎么判断。
 *     这类内容由本 App 创作，与测评题目的性质相同，不属于「行业数据」。
 *   - 不包含任何行业统计数字；行业本身的判断仍以行业卡片为准（含来源）。
 *   - 每天任务 ≤ 30 分钟、宿舍/工位可完成（docs/FLOW.md 的硬约束）。
 *   - 假设是**示例**：示范「可证伪」的写法，用户开始前可以改成自己的。
 */

export interface ExperimentTemplate {
  id: string
  /** 展示用标题，以「7 天：」开头 */
  title: string
  /** 探索方向，写入 experiment.direction */
  direction: string
  /** 关联的行业卡片 id；通用模板为 null */
  industry: string | null
  /**
   * 可证伪假设的示例。
   * 开始实验时预填，鼓励用户改写成自己的 —— 但写得太笼统也可以直接用。
   */
  hypothesis: string
  /** 7 天任务清单，每天一条，长度固定 7 */
  days: string[]
  /** 适合谁试：一句话，帮用户对号入座 */
  suitable: string
  tags: string[]
}

